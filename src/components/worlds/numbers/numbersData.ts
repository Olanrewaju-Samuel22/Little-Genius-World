export const getNumberByValue = (val: number): NumberItem => {
  return NUMBERS_DATA.find((n) => n.number === val) || NUMBERS_DATA[0];
};

export const getLocalizedNumberName = (item: NumberItem, lang: string): string => {
  switch (lang) {
    case 'ha':
      return item.hausaWord;
    case 'yo':
      return item.yorubaWord;
    case 'ig':
      return item.igboWord;
    default:
      return item.word;
  }
};
