export const getAnimalById = (id: string): AnimalItem => {
  return ANIMALS_DATA.find((a) => a.id === id) || ANIMALS_DATA[0];
};

export const getLocalizedAnimalName = (animal: AnimalItem, lang: string): string => {
  switch (lang) {
    case 'yo':
      return animal.yo;
    case 'ha':
      return animal.ha;
    case 'ig':
      return animal.ig;
    default:
      return animal.name;
  }
};
